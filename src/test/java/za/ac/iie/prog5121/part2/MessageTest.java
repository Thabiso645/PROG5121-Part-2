package za.ac.iie.prog5121.part1;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import org.junit.jupiter.api.Test;

/**
 *
 * @author thabiso
 */
public class MessageTest {
    // ==========================================
    // TEST CASE 1: VALID CONTENT ASSERTIONS
    // ==========================================
    
    @Test
    public void testMessageLengthSuccess() {
        // Test Data: Valid text under 250 characters boundary limit
        Message msg = new Message(0, "+27718693002", "Hi Mike, can you join us for dinner tonight?");
        String expected = "Message ready to send.";
        assertEquals(expected, msg.checkMessageLength());
    }

    @Test
    public void testRecipientCellFormattedCorrectly() {
        // Test Data: Properly structured international phone format code matching pattern
        Message msg = new Message(0, "+27718693002", "Hi Mike, can you join us for dinner tonight?");
        String expected = "Cell phone number successfully captured.";
        assertEquals(expected, msg.checkRecipientCell());
    }

    // ==========================================
    // TEST CASE 2: INVALID CONTENT ASSERTIONS
    // ==========================================

    @Test
    public void testMessageLengthFailure() {
        // Test Data: Purposefully generating content exceeding 250 character limitations boundary hook
        StringBuilder boundaryBreaker = new StringBuilder();
        for (int i = 0; i < 260; i++) {
            boundaryBreaker.append("x");
        }
        Message msg = new Message(0, "+27718693002", boundaryBreaker.toString());
        
        // Exceeds 250 characters by exactly 10 characters
        String expected = "Message exceeds 250 characters by 10 characters, please reduce the size.";
        assertEquals(expected, msg.checkMessageLength());
    }

    @Test
    public void testRecipientCellFormattedIncorrectly() {
        // Test Data: Wrong local number format rule failing the international verification check 
        Message msg = new Message(1, "08575975889", "Hi Keegan, did you receive the payment?");
        String expected = "Cell phone number is incorrectly formatted or does not contain an international code. Please correct the number and try again.";
        assertEquals(expected, msg.checkRecipientCell());
    }

    // ==========================================
    // STRUCTURAL & HASH INTEGRITY CHECKS
    // ==========================================

    @Test
    public void testMessageIDGenerationBounds() {
        // Verifies the random autogenerated message ID code exists and conforms to standard length bounds constraint rule
        Message msg = new Message(0, "+27718693002", "Hi Mike, can you join us for dinner tonight?");
        assertTrue(msg.checkMessageID());
    }

    @Test
    public void testMessageHashFormattingLayout() {
        // Validates message hash format parses words and converts them cleanly to UPPERCASE
        Message msg = new Message(0, "+27718693002", "Hi Mike, can you join us for dinner tonight?");
        String targetHash = msg.createMessageHash();
        
        // Ensure first word "HI" and last word "TONIGHT" are correctly bound and forced to upper register strings
        assertTrue(targetHash.contains("HI"), "Hash formatting missing the uppercase definition marker for the first input token.");
        assertTrue(targetHash.contains("TONIGHT"), "Hash formatting missing the uppercase definition marker for the trailing input token.");
    }
}
